import fs from 'node:fs';
import path from 'node:path';
import {spawn,spawnSync} from 'node:child_process';
import {research,repository,variant,dependencyJar,classes,filesBelow,sha256} from './build_controlled.mjs';

const [configArgument,outputArgument,corpusArgument] = process.argv.slice(2);
if (!configArgument || !outputArgument) throw new Error('Usage: node scripts/run_experiment.mjs config.json runs/NAME [corpus.json]');
const configFile = path.resolve(configArgument);
const output = path.resolve(outputArgument);
if (!output.startsWith(research+path.sep)) throw new Error('All new output must stay inside the research folder');
if (fs.existsSync(output)) throw new Error('Refusing to reuse an existing output directory');
const corpus = path.resolve(corpusArgument ?? path.join(repository,'resources/sampler-140626/data/Umass-sub-corpus/pluieTriples_2013_01_06_5.json'));
const config = JSON.parse(fs.readFileSync(configFile,'utf8'));
if (!Number.isSafeInteger(config.seed)) throw new Error('seed must be an explicit safe integer');
const buildHashes = JSON.parse(fs.readFileSync(path.join(variant,'build/source_sha256.json'),'utf8'));
const currentHashes = Object.fromEntries(filesBelow(path.join(variant,'src')).map(f=>[path.relative(variant,f),sha256(f)]));
if (JSON.stringify(buildHashes)!==JSON.stringify(currentHashes)) throw new Error('Source changed after compilation; rebuild first');
fs.mkdirSync(output,{recursive:true});
fs.copyFileSync(configFile,path.join(output,'config.json'));
fs.copyFileSync(path.join(variant,'build/source_sha256.json'),path.join(output,'source_sha256.json'));
fs.copyFileSync(path.join(variant,'build/build.json'),path.join(output,'build.json'));
// A run must not lazy-load classes from a build directory another experiment can replace.
const runClasses=path.join(output,'runtime_classes');
fs.cpSync(classes,runClasses,{recursive:true});
fs.writeFileSync(path.join(output,'logback.xml'),'<configuration><root level="OFF"/></configuration>\n');
const archive=spawnSync('tar',['-czf',path.join(output,'source_snapshot.tar.gz'),'-C',variant,'src'],{encoding:'utf8'});
if (archive.status!==0) throw new Error(archive.stderr);
const args=['-ea','-Xmx4g',`-Dlogback.configurationFile=${path.join(output,'logback.xml')}`,'-cp',`${runClasses}:${dependencyJar}`,'org.ucb.generative_ie.experiments.ControlledNYT',path.join(output,'config.json'),corpus,output];
const manifest={status:'running',started_at:new Date().toISOString(),config,corpus,corpus_sha256:sha256(corpus),dependency_jar:dependencyJar,dependency_sha256:sha256(dependencyJar),source_archive_sha256:sha256(path.join(output,'source_snapshot.tar.gz')),java:spawnSync('java',['-version'],{encoding:'utf8'}).stderr.trim(),command:{executable:'java',args,cwd:output},seed_control:'All active NYT random streams explicitly seeded; ProbMap insertion order fixed. Exact replay supported on the recorded Java/dependency versions.',prior:'Pool-dependent fixed-slot prior retained unless a future explicitly named model variant changes it.'};
const manifestFile=path.join(output,'run.json');
fs.writeFileSync(manifestFile,JSON.stringify(manifest,null,2)+'\n');
const started=Date.now();
const stdout=fs.openSync(path.join(output,'stdout.log'),'w'), stderr=fs.openSync(path.join(output,'stderr.log'),'w');
const child=spawn('java',args,{cwd:output,stdio:['ignore',stdout,stderr]});
const result=await new Promise((resolve,reject)=>{child.on('error',reject);child.on('close',(code,signal)=>resolve({code,signal}));});
fs.closeSync(stdout); fs.closeSync(stderr);
Object.assign(manifest,result,{status:result.code===0?'complete':'failed',finished_at:new Date().toISOString(),elapsed_seconds:(Date.now()-started)/1000});
manifest.outputs=Object.fromEntries(filesBelow(output).filter(f=>!['run.json','source_snapshot.tar.gz'].includes(path.basename(f))).map(f=>[path.relative(output,f),sha256(f)]));
fs.writeFileSync(manifestFile,JSON.stringify(manifest,null,2)+'\n');
console.log(JSON.stringify({output,...result,elapsed_seconds:manifest.elapsed_seconds}));
if(result.code!==0) process.exitCode=1;
